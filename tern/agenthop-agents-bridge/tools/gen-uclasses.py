#!/usr/bin/env python3 -I
"""Regenerate uclasses.luau: exact codepoint ranges of \\s \\w \\d \\p{Alphabetic} as the Rust regex crate defines them, probed through
ripgrep (same engine herdr uses). Usage: gen-uclasses.py /path/to/rg > uclasses.luau"""
import subprocess, re, sys
RG = sys.argv[1]
ver = subprocess.run([RG, "--version"], capture_output=True, text=True).stdout.splitlines()[0]
def ranges(cls):
    cps = [c for c in range(1, 0x110000) if not (0xD800 <= c <= 0xDFFF) and c not in (10, 13)]
    data = ("\n".join(chr(c) for c in cps) + "\n").encode("utf-8")
    r = subprocess.run([RG, "--no-config", "--text", "-n", "--no-filename", "-e", "^" + cls + "$", "-"], input=data, capture_output=True)
    hits = set()
    for m in re.finditer(rb"(?:^|\n)(\d+):", r.stdout):
        n = int(m.group(1))
        if 1 <= n <= len(cps): hits.add(cps[n - 1])
    out, s, prev = [], None, None
    for c in sorted(hits):
        if s is None: s = prev = c
        elif c == prev + 1: prev = c
        else: out.append((s, prev)); s = prev = c
    if s is not None: out.append((s, prev))
    return out
print(f"-- GENERATED by tools/gen-uclasses.py from {ver} (Rust regex crate classes). Do not hand-edit; regenerate.")
print("-- Each class = sorted {lo, hi, lo, hi, ...} inclusive codepoint ranges (flat for size). \\n and \\r probed separately.")
print("return {")
for name, cls in (("space", r"\s"), ("word", r"\w"), ("digit", r"\d"), ("alpha", r"\p{Alphabetic}")):
    rs = ranges(cls)
    if name == "space":  # \s contains \n \r in Rust; the line probe cannot test them — add, then merge adjacent ranges
        merged = []
        for lo, hi in sorted(rs + [(10, 10), (13, 13)]):
            if merged and lo <= merged[-1][1] + 1: merged[-1] = (merged[-1][0], max(merged[-1][1], hi))
            else: merged.append((lo, hi))
        rs = merged
    flat = ",".join(f"{a},{b}" for a, b in rs)
    print(f"  {name} = {{{flat}}},")
print("}")
