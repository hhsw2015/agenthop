#!/usr/bin/env python3 -I
"""Regenerate manifests.luau from herdr's manifest TOML files. Usage: gen-manifests.py <herdr>/src/detect/manifests > manifests.luau"""
import tomllib, glob, os, sys, subprocess
src = sys.argv[1]
def lua(v, ind=""):
    if isinstance(v, bool): return "true" if v else "false"
    if isinstance(v, int): return str(v)
    if isinstance(v, str):
        return '"' + v.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'
    if isinstance(v, list):
        return "{ " + ", ".join(lua(x, ind) for x in v) + " }"
    if isinstance(v, dict):
        return "{ " + ", ".join(f'["{k}"] = {lua(x, ind)}' for k, x in v.items()) + " }"
    raise TypeError(v)
commit = subprocess.run(["git", "-C", src, "rev-parse", "--short", "HEAD"], capture_output=True, text=True).stdout.strip()
print(f"""-- GENERATED by tools/gen-manifests.py from herdr ({commit}) src/detect/manifests/*.toml. Do not hand-edit; regenerate.
-- Source: herdr, local clone ~/Dev/herdr at commit {commit}. License: AGPL-3.0-or-later (see that repo's LICENSE).
-- Translated verbatim (data only): every rule keeps id/state/priority/region/contains/any/all/not/line_regex/regex/visible_*/skip_state_update.
-- User ruling 2026-10-15: translate the originals directly; this header is the honest attribution, not a risk assessment.
local M = {{}}""")
for f in sorted(glob.glob(os.path.join(src, "*.toml"))):
    d = tomllib.load(open(f, "rb"))
    print(f'M["{d["id"]}"] = {{ id = {lua(d["id"])}, version = {lua(d.get("version",""))}, aliases = {lua(d.get("aliases", []))}, rules = {{')
    for r in d["rules"]:
        print("  " + lua(r) + ",")
    print("} }")
print("return M")
